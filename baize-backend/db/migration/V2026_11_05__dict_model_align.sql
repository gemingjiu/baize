-- =============================================================================
-- V2026_11_05__dict_model_align.sql
--
-- 用途：落地 2026-11-04 字典模块规划（用户决策 1A/2删/3批量/4全量/5先13类）——
--       字典表模型对齐"平台内置 + 租户自定义兜底"混合模型，补通用字典种子，
--       让字典真正"生效"（此前表为空、前端零消费、读接口权限错位、缓存键跨租户）。
--
-- 【决策依据】
--   D1=1A：sys_dict_type / sys_dict_data 增加 is_builtin（平台内置 / 租户自定义），
--          读路径按"租户自定义 → 平台内置兜底"合并解析（Java 侧同 commit 实现）。
--   D2=删：删除 RuoYi 遗留的 css_class / list_class（前端样式不进 DB；antd 前端用不上）。
--   D3=批量：后端新增 /system/dict/data/all 批量读接口（登录即可见），配合前端全局缓存。
--   D4=全量：前端全量替换 10 页 28+ 处硬编码枚举。
--   D5=先 14 类：种子覆盖当前全站硬编码所需全部字典类型。
--
-- 【表结构变更】
--   sys_dict_type：+ is_builtin（内置不可删除）；dict_type 补 NOT NULL。
--   sys_dict_data：+ is_builtin；dict_type / dict_value 补 NOT NULL；
--                  DROP COLUMN css_class / list_class（存量列，无消费方）。
--
-- 【种子规划】（tenant_id = 平台 nil UUID，is_builtin='1'；ID 段：类型 N=4001..4014，数据 N=4101..4140，
--   遵循全库约定 逻辑id N → '00000000-0000-7000-' + hex16(N)，与既有种子 1..3016 段无冲突）
--   1  sys_normal_disable 通用状态      0=正常,1=停用
--   2  sys_yes_no         系统是否      Y=是,N=否
--   3  sys_user_sex       用户性别      0=男,1=女,2=未知
--   4  sys_notice_type    通知类型      1=通知,2=公告
--   5  sys_oper_type      操作类型      1=新增..9=清空数据（与 operlog 页现值一致）
--   6  sys_oper_status    操作状态      0=成功,1=失败（operlog/loginlog 共用）
--   7  sys_job_status     任务状态      0=正常,1=暂停
--   8  sys_job_concurrent 任务是否并发  0=允许,1=禁止
--   9  sys_config_type    参数系统内置  Y=是,N=否
--   10 sys_role_type      角色类型      0=平台角色,1=租户角色
--   11 sys_data_scope     数据权限范围  1=全部..5=仅本人（与 DataScopeConstant 一致）
--   12 sys_menu_type      菜单类型      0=目录,1=菜单,2=按钮
--   13 sys_defaulted      是否默认      0=否,1=是
--
-- 【ON CONFLICT 仲裁联动】
--   init 对字典种子走 ON CONFLICT (id)（主键仲裁）不受影响；本脚本种子用裸
--   ON CONFLICT DO NOTHING（容忍 id 冲突与 uk(tenant_id,dict_type,dict_value) 冲突两种情况，
--   存量库若有业务自建的同值行则跳过该种子行，保证幂等不硬失败）。
--   注意：V2026_11_03 已把 uk_sys_dict_data_tenant_type_value / uk_sys_dict_type_tenant_dict_type
--   转为 partial unique index（WHERE deleted='0'），种子行 deleted='0' 参与判重，语义不变。
--
-- 【幂等性】
--   - ALTER 全部 IF [NOT] EXISTS / DO 块判存在；重复执行 0 变更；
--   - SET NOT NULL 前先验 NULL 行数，有脏数据只 NOTICE 跳过不硬失败；
--   - 种子 INSERT 裸 ON CONFLICT DO NOTHING，二跑 0 行。
--
-- 【执行方式】
--   psql -v ON_ERROR_STOP=1 -f 本文件。
--
-- 【执行后自检】
--   SELECT dict_type, dict_name, is_builtin FROM "baize-system".sys_dict_type ORDER BY sort;
--   -- 预期 ≥14 行，is_builtin 全为 '1'
--   SELECT dict_type, count(*) FROM "baize-system".sys_dict_data
--    WHERE is_builtin='1' GROUP BY dict_type ORDER BY dict_type;
--   -- 预期 14 组共 40 行
--   SELECT column_name FROM information_schema.columns
--    WHERE table_schema='baize-system' AND table_name='sys_dict_data'
--      AND column_name IN ('css_class','list_class');
--   -- 预期 0 行（已删除）
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS "baize-system";

-- -----------------------------------------------------------------------------
-- 1. sys_dict_type：加 is_builtin + dict_type 补 NOT NULL
-- -----------------------------------------------------------------------------
ALTER TABLE "baize-system".sys_dict_type
    ADD COLUMN IF NOT EXISTS is_builtin varchar(1) DEFAULT '0' NOT NULL;

COMMENT ON COLUMN "baize-system".sys_dict_type.is_builtin IS '是否内置字典类型;0:租户自定义,1:平台内置（内置不可删除）';

DO $$
DECLARE
    v_reg   regclass := to_regclass('"baize-system".sys_dict_type');
    v_nulls bigint;
BEGIN
    IF v_reg IS NULL THEN
        RAISE NOTICE 'DICT_ALIGN 跳过（sys_dict_type 不存在）';
        RETURN;
    END IF;
    EXECUTE 'SELECT count(*) FROM "baize-system".sys_dict_type WHERE dict_type IS NULL' INTO v_nulls;
    IF v_nulls > 0 THEN
        RAISE NOTICE 'DICT_ALIGN 跳过 NOT NULL：sys_dict_type.dict_type 存在 % 行 NULL，请先清洗', v_nulls;
    ELSIF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'baize-system' AND table_name = 'sys_dict_type'
                     AND column_name = 'dict_type' AND is_nullable = 'NO') THEN
        RAISE NOTICE 'DICT_ALIGN 跳过（sys_dict_type.dict_type 已 NOT NULL）';
    ELSE
        ALTER TABLE "baize-system".sys_dict_type ALTER COLUMN dict_type SET NOT NULL;
        RAISE NOTICE 'DICT_ALIGN 已置 sys_dict_type.dict_type NOT NULL';
    END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. sys_dict_data：加 is_builtin + dict_type/dict_value 补 NOT NULL + 删样式列
-- -----------------------------------------------------------------------------
ALTER TABLE "baize-system".sys_dict_data
    ADD COLUMN IF NOT EXISTS is_builtin varchar(1) DEFAULT '0' NOT NULL;

COMMENT ON COLUMN "baize-system".sys_dict_data.is_builtin IS '是否内置字典项;0:租户自定义,1:平台内置（平台维护，租户不可删）';

DO $$
DECLARE
    v_reg    regclass := to_regclass('"baize-system".sys_dict_data');
    v_nulls1 bigint;
    v_nulls2 bigint;
BEGIN
    IF v_reg IS NULL THEN
        RAISE NOTICE 'DICT_ALIGN 跳过（sys_dict_data 不存在）';
        RETURN;
    END IF;
    EXECUTE 'SELECT count(*) FROM "baize-system".sys_dict_data WHERE dict_type IS NULL' INTO v_nulls1;
    EXECUTE 'SELECT count(*) FROM "baize-system".sys_dict_data WHERE dict_value IS NULL' INTO v_nulls2;
    IF v_nulls1 > 0 OR v_nulls2 > 0 THEN
        RAISE NOTICE 'DICT_ALIGN 跳过 NOT NULL：sys_dict_data 存在 dict_type NULL % 行、dict_value NULL % 行，请先清洗', v_nulls1, v_nulls2;
    ELSE
        IF EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = 'baize-system' AND table_name = 'sys_dict_data'
                      AND column_name = 'dict_type' AND is_nullable = 'YES') THEN
            ALTER TABLE "baize-system".sys_dict_data ALTER COLUMN dict_type SET NOT NULL;
            RAISE NOTICE 'DICT_ALIGN 已置 sys_dict_data.dict_type NOT NULL';
        END IF;
        IF EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = 'baize-system' AND table_name = 'sys_dict_data'
                      AND column_name = 'dict_value' AND is_nullable = 'YES') THEN
            ALTER TABLE "baize-system".sys_dict_data ALTER COLUMN dict_value SET NOT NULL;
            RAISE NOTICE 'DICT_ALIGN 已置 sys_dict_data.dict_value NOT NULL';
        END IF;
    END IF;
END $$;

-- RuoYi 遗留前端样式列（antd 前端无消费方，决策 D2 删除）
ALTER TABLE "baize-system".sys_dict_data DROP COLUMN IF EXISTS css_class;
ALTER TABLE "baize-system".sys_dict_data DROP COLUMN IF EXISTS list_class;

