-- 用途：种子 6 个预置角色（2 个平台 + 4 个租户模板）及其菜单绑定。
--
-- 【背景】
--   此前系统仅 admin 一个内置角色，非超管用户权限只能靠管理员手工建角色
--   逐个勾菜单，开箱即用性差。本批角色按「最小权限 + 职责分离」规划：
--     - 平台侧：ops（运维）、auditor（审计）——管基础设施不碰业务配置
--     - 租户侧（模板种子，落 master 租户 0）：tenant_admin（内置不可删）、
--       hr（人事）、dept_manager（部门主管，数据权限 4）、employee（最小基线）
--
-- 【角色明细】
--   id=2 ops            平台 运维管理员  data_scope=1  监控目录+定时任务，无业务写权限
--   id=3 auditor        平台 审计员      data_scope=1  日志查询/导出只读，不给删除
--   id=4 tenant_admin   租户 租户管理员  data_scope=1  租户内系统管理闭环（内置不可删），
--                                                     刻意排除租户管理/权限管理/监控/工具
--   id=5 hr             租户 人事专员    data_scope=1  用户全套+部门查询+岗位全套+公告查询
--   id=6 dept_manager   租户 部门主管    data_scope=4  本部门及以下；仅用户查询+公告查询
--   id=7 employee       租户 普通员工    data_scope=5  公告查询+修改密码（个人中心改密）
--
-- 【安全性论证】
--   1. 幂等：INSERT ... ON CONFLICT (id) DO NOTHING / (tenant_id, role_id, menu_id)
--      DO NOTHING，重复执行 0 行变更。
--   2. 不触碰 admin（id=1）及其绑定；超管白名单
--      baize.security.super-admin-role-codes:admin 仅 admin 命中 *:*:*，
--      新角色全部走正常多角色聚合签发（e5f673c）。
--   3. id 取 2~7：与 admin(id=1) 错开；执行前请确认未被占用
--      （SELECT id FROM "baize-system".sys_role WHERE id BETWEEN 2 AND 7;）。
--   4. tenant_admin 标记 is_builtin='1'——removeById 双守卫（内置拒绝+占用拒绝）
--      防止租户管理员被误删导致租户失管。
--   5. 员工角色 employee 仅含 1008 修改密码按钮行（system:user:updatePwd），
--      不绑用户管理菜单页，个人中心改密不受影响。
--
-- 【执行方式】
--   psql 或任意 JDBC 客户端整文件执行。
--
-- 【执行后自检】
--   SELECT id, role_code, role_name, role_type, is_builtin, data_scope
--     FROM "baize-system".sys_role WHERE id BETWEEN 2 AND 7 ORDER BY id;
--   -- 预期 6 行，role_type/id=2,3 为 0，其余为 1；is_builtin 仅 id=4 为 1
--   SELECT role_id, count(*) FROM "baize-system".sys_role_menu
--    WHERE role_id BETWEEN 2 AND 7 GROUP BY role_id ORDER BY role_id;
-- =============================================================================

